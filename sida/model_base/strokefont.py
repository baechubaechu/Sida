ADVANCE = 5.5  # grid units from one letter to the next


def text_width(text: str, height: float) -> float:
    return (len(text) * ADVANCE - (ADVANCE - 4)) * height / 6 if text else 0.0


def strokes(text: str, x: float, y: float, height: float) -> list[list[tuple[float, float]]]:
    k = height / 6
    lines = []
    for i, ch in enumerate(text):
        glyph = GLYPHS.get(ch)
        if glyph is None:
            raise ValueError(f"no stroke glyph for {ch!r}")
        ox = x + i * ADVANCE * k
        lines += [[(ox + gx * k, y + gy * k) for gx, gy in line] for line in glyph]
    return lines
